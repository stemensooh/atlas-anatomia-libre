// Migraciones del esquema en PostgreSQL (D-016). Equivalen al esquema v4 de SQLite
// (schema-sqlite.ts) con tipos propios de PostgreSQL. La tabla schema_migrations guarda las
// aplicadas. Nunca se edita una migración ya publicada: los cambios van en una nueva, en los dos motores.

export const POSTGRES_MIGRATIONS: string[] = [
  // v1: esquema completo (cuentas, cuestionarios, intentos, vistas y notas)
  `
    CREATE TABLE users (
      id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username       TEXT NOT NULL,
      password_hash  TEXT NOT NULL,
      role           TEXT NOT NULL DEFAULT 'estudiante' CHECK (role IN ('estudiante', 'docente', 'admin')),
      is_active      BOOLEAN NOT NULL DEFAULT TRUE,
      created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
      last_login_at  TIMESTAMPTZ
    );
    -- El nombre de usuario no distingue mayúsculas (en SQLite: COLLATE NOCASE).
    CREATE UNIQUE INDEX users_username_lower ON users (lower(username));

    -- Solo se guarda el hash SHA-256 del token de sesión.
    CREATE TABLE sessions (
      token_hash  TEXT PRIMARY KEY,
      user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
      expires_at  TIMESTAMPTZ NOT NULL
    );
    CREATE INDEX idx_sessions_user ON sessions(user_id);

    CREATE TABLE quizzes (
      id          TEXT PRIMARY KEY,
      title       TEXT NOT NULL,
      subtitle    TEXT NOT NULL DEFAULT '',
      source      TEXT NOT NULL CHECK (source IN ('seed', 'manual', 'generated')),
      user_id     INTEGER REFERENCES users(id) ON DELETE CASCADE,
      is_public   BOOLEAN NOT NULL DEFAULT FALSE,
      created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE INDEX idx_quizzes_user ON quizzes(user_id);

    CREATE TABLE questions (
      id                   TEXT NOT NULL,
      quiz_id              TEXT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
      position             INTEGER NOT NULL,
      type                 TEXT NOT NULL CHECK (type IN ('find3d', 'multipleChoice')),
      prompt               TEXT NOT NULL,
      hint                 TEXT NOT NULL DEFAULT '',
      body_sex             TEXT NOT NULL CHECK (body_sex IN ('male', 'female')),
      enabled_systems      JSONB NOT NULL,
      target_structure_id  TEXT NOT NULL,
      target_name_es       TEXT NOT NULL,
      options              JSONB,
      explanation          TEXT NOT NULL DEFAULT '',
      PRIMARY KEY (quiz_id, id)
    );
    CREATE INDEX idx_questions_quiz ON questions(quiz_id, position);

    CREATE TABLE quiz_attempts (
      id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      quiz_id      TEXT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
      user_id      INTEGER REFERENCES users(id) ON DELETE CASCADE,
      score        INTEGER NOT NULL,
      total        INTEGER NOT NULL,
      answers      JSONB NOT NULL,
      finished_at  TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE INDEX idx_attempts_quiz ON quiz_attempts(quiz_id, finished_at);
    CREATE INDEX idx_attempts_user ON quiz_attempts(user_id, finished_at);

    CREATE TABLE saved_views (
      id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      name        TEXT NOT NULL,
      state       JSONB NOT NULL,
      created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
    );
    CREATE INDEX idx_views_user ON saved_views(user_id, updated_at);

    CREATE TABLE structure_notes (
      user_id       INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      structure_id  TEXT NOT NULL,
      note          TEXT NOT NULL,
      updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
      PRIMARY KEY (user_id, structure_id)
    );
  `,
];
